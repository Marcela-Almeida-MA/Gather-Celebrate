-- =========================================================
-- 9. UPDATED_AT
-- Atualiza automaticamente updated_at
-- =========================================================

create or replace function public.update_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;


create trigger profiles_updated_at
before update on public.profiles
for each row
execute function public.update_updated_at();


create trigger themes_updated_at
before update on public.themes
for each row
execute function public.update_updated_at();


create trigger invitations_updated_at
before update on public.invitations
for each row
execute function public.update_updated_at();


create trigger timeline_items_updated_at
before update on public.timeline_items
for each row
execute function public.update_updated_at();


-- =========================================================
-- 10. PROFILE AUTOMÁTICO
-- Cria um profile quando um usuário se cadastra
-- =========================================================

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (
    id,
    name,
    email
  )
  values (
    new.id,
    new.raw_user_meta_data ->> 'name',
    new.email
  );

  return new;
end;
$$;


create trigger on_auth_user_created
after insert on auth.users
for each row
execute function public.handle_new_user();


