-- =========================================================
-- 1. PROFILES
-- Complementa o usuário criado pelo Supabase Auth
-- =========================================================

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- =========================================================
-- 2. EVENT TYPES
-- Exemplos: aniversário, casamento, chá de bebê...
-- =========================================================

create table public.event_types (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);


-- =========================================================
-- 3. THEMES
-- Tema visual independente do tipo de evento
-- =========================================================

create table public.themes (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  description text,
  category text,
  thumbnail text,
  preview_image text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- =========================================================
-- 4. INVITATIONS
-- Convites criados pelos usuários
-- =========================================================

create table public.invitations (
  id uuid primary key default gen_random_uuid(),

  user_id uuid not null
    references public.profiles(id)
    on delete cascade,

  event_type_id bigint
    references public.event_types(id)
    on delete set null,

  theme_id bigint
    references public.themes(id)
    on delete set null,

  slug text not null unique,

  title text,
  description text,
  story text,

  event_date date,
  event_time time,

  is_online boolean not null default false,
  online_platform text,
  online_url text,

  location text,
  address text,
  city text,
  state text,

  pix_key text,
  pix_name text,
  pix_qrcode text,

  status text not null default 'draft'
    check (status in ('draft', 'published', 'archived')),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- =========================================================
-- 5. INVITATION PHOTOS
-- Fotos utilizadas no convite
-- =========================================================

create table public.invitation_photos (
  id uuid primary key default gen_random_uuid(),

  invitation_id uuid not null
    references public.invitations(id)
    on delete cascade,

  url text not null,

  type text not null default 'gallery'
    check (
      type in (
        'cover',
        'story',
        'timeline',
        'gallery'
      )
    ),

  position integer not null default 0,

  caption text,

  created_at timestamptz not null default now()
);


-- =========================================================
-- 6. TIMELINE
-- Linha do tempo / história do evento
-- =========================================================

create table public.timeline_items (
  id uuid primary key default gen_random_uuid(),

  invitation_id uuid not null
    references public.invitations(id)
    on delete cascade,

  title text not null,
  description text,

  date date,

  image_url text,

  position integer not null default 0,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- =========================================================
-- 7. GIFTS
-- Sugestões de presentes
-- =========================================================

create table public.gifts (
  id uuid primary key default gen_random_uuid(),

  invitation_id uuid not null
    references public.invitations(id)
    on delete cascade,

  name text not null,
  description text,

  value numeric(10,2),

  image text,

  position integer not null default 0,

  active boolean not null default true,

  created_at timestamptz not null default now()
);


